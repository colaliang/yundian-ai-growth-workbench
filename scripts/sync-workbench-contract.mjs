import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {loadUiContract} from '../src/navigation/ui-contract.ts';
const args=process.argv.slice(2);const at=args.indexOf('--root');
const root=at<0?path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'):path.resolve(args[at+1]);
const check=args.includes('--check');
const c=loadUiContract(root);
const generated='// Generated by scripts/sync-workbench-contract.mjs; public fixed labels only.\n'+[['WORKBENCH_NAVIGATION',c.navigation],['PROMOTION_MODULE_IDS',c.promotionModuleIds],['FREE_MODULE_IDS',c.freeModuleIds]].map(([name,value])=>'export const '+name+'='+JSON.stringify(value,null,2)+';\n').join('');
const start='<!-- workbench-ui:begin -->',end='<!-- workbench-ui:end -->';
const block=start+'\n一级导航：'+c.navigation.map(x=>x[1]).join('、')+'。\n营销推广包含12个子项目，各占一行；内容运营只在一级出现。保留13个项目、15个执行阶段及历史SEO/GEO入口。\n免费项目：市场调研、产品机会、客户背调、销售反馈，无专家咨询窗口；其余项目页末按钮按需打开，二维码仍为占位，不自动发送客户资料。\n'+end;
let drift=false;
function output(file,expected){const target=path.join(root,file);const current=fs.existsSync(target)?fs.readFileSync(target,'utf8'):null;if(current===expected)return;if(check){console.error('UI contract drift: '+file);drift=true;}else{fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,expected);}}
output('web/workbench-ui.js',generated);
for(const file of ['skills/yundian-growth-workbench/references/BUILD_BRIEF.md','README.md','docs/module-workspace-guide.zh-CN.md']){
 const current=fs.readFileSync(path.join(root,file),'utf8');const normalized=current;
 const begin=normalized.indexOf(start),finish=normalized.indexOf(end);
 let expected;
 if(begin>=0&&finish>begin)expected=normalized.slice(0,begin)+block+normalized.slice(finish+end.length);
 else if(begin>=0||finish>=0)throw new Error('Malformed UI contract markers: '+file);
 else if(file.includes('BUILD_BRIEF')){if(!/^导航：.*$/m.test(normalized))throw new Error('Missing official UI contract markers or legacy navigation: '+file);expected=normalized.replace(/^导航：.*$/m,block+'\n\n全域技能范围按MODULES/registry，历史标识兼容。云店+logo、白底低饱和灰和蓝色操作，窄屏单列/折叠菜单，空白项目不预置客户、线索、收入或模拟成功。');}
 else expected=normalized.trimEnd()+'\n\n'+block+'\n';
 output(file,expected);
}
if(drift)process.exitCode=1;
